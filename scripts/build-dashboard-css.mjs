// Builds src/app/dashboard/dashboard.css: only the Tailwind classes used by the leads
// dashboard (src/app/dashboard), without Tailwind's page reset, so the public site's
// own CSS is untouched. Run after changing classes in the dashboard:
//   npm run dashboard:css
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.join(root, 'src/app/dashboard/dashboard.css');
const input = `
@import "tailwindcss/theme.css" theme(inline);
@import "tailwindcss/utilities.css" source(none);
@source "./";
`;
const result = await postcss([tailwind({ base: path.join(root, 'src/app/dashboard') })]).process(input, {
  from: path.join(root, 'src/app/dashboard/_tailwind-input.css'),
});
// Every rule is scoped to the dashboard (".dash" and anything inside it), which also makes it
// win over the site's own unscoped styles for buttons, links and headings.
const scoped = postcss.parse(result.css);
scoped.walkRules((rule) => {
  if (rule.parent && rule.parent.type === 'rule') return; // nested "&:hover" parts follow their parent
  if (rule.selectors.some((sel) => sel.startsWith(':root') || sel.startsWith(':host'))) return;
  rule.selectors = rule.selectors.flatMap((sel) => {
    if (sel === '*') return ['.dash', '.dash *']; // Tailwind's defaults for every element
    if (/^[*:]/.test(sel)) return [`.dash ${sel}`]; // "::before", "::backdrop"…
    return [`.dash ${sel}`, `.dash${sel}`]; // the class on .dash itself, or anything inside it
  });
});
scoped.walkAtRules('layer', (layer) => layer.replaceWith(layer.nodes)); // no CSS layers: plain rules
// globals.css removes every border on the site with `border-width: 0 !important`;
// the dashboard's own border widths have to be !important too (scoped, so they win only here).
scoped.walkDecls(/^border(-(top|right|bottom|left|x|y|block|inline)(-(start|end))?)?-width$/, (decl) => {
  decl.important = true;
});
const header = '/* Generated by scripts/build-dashboard-css.mjs — do not edit; run `npm run dashboard:css`. */\n';
const reset = `
/* A small reset for the dashboard only (the public site keeps its own styles). */
.dash, .dash *, .dash ::before, .dash ::after { box-sizing: border-box; }
.dash { font-family: var(--font-inter), system-ui, sans-serif; line-height: 1.5; -webkit-font-smoothing: antialiased; }
.dash h1, .dash h2, .dash p, .dash dl, .dash dd, .dash ol { margin: 0; }
.dash ol { list-style: none; padding: 0; }
.dash a { text-decoration: none; }
.dash button, .dash input, .dash select, .dash textarea { font: inherit; color: inherit; }
.dash button { cursor: pointer; background: transparent; border: 0; }
.dash button:disabled { cursor: default; }
.dash table { border-collapse: collapse; }
`;
await writeFile(out, header + scoped.toString() + reset);
const prev = await readFile(out, 'utf8');
console.log(`Wrote ${path.relative(root, out)} (${(prev.length / 1024).toFixed(1)} KB)`);
